// 可选浏览器检查：PLAYWRIGHT_MODULE 指向现有 playwright 包，无需加入运行依赖。
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createApp } from '../server/app.mjs';
import { projectRoot } from '../server/store.mjs';
import { unzipSync, strFromU8 } from 'fflate';
import http from 'node:http';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const qaDir = path.join(projectRoot, '.data', 'qa');
await fs.mkdir(qaDir, { recursive: true });
const dataDir = await fs.mkdtemp(path.join(qaDir, 'browser-run-'));
const development = process.argv.includes('--dev');
const app = await createApp({ dataDir, development });
let vite;
if (development) {
  const { attachDevelopment } = await import('../server/development.mjs');
  vite = await attachDevelopment(app);
}
await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${app.server.address().port}`;
let browser;
let exportServer;
const errors = [];
const failures = [];
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, acceptDownloads: true });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('response', response => { if (response.status() >= 500) failures.push(`${response.status()} ${response.url()}`); });
  await page.goto(base); await page.getByRole('heading', { name: /越过雾海/ }).waitFor();
  await page.screenshot({ path: path.join(qaDir, 'homepage-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '下一张', exact: true }).click();
  assert.equal(await page.locator('[data-current]').textContent(), '02');
  await page.getByRole('button', { name: '暂停自动轮播' }).click();
  assert.equal(await page.getByRole('button', { name: '开始自动轮播' }).getAttribute('aria-pressed'), 'true');
  await page.goto(`${base}/admin`);
  await page.getByRole('heading', { name: '创建你的工作台' }).waitFor();
  await page.getByLabel('管理员账号').fill('tester');
  await page.locator('input[name="password"]').fill('browser-test-password');
  await page.getByLabel('确认密码').fill('browser-test-password');
  await page.getByRole('button', { name: '创建账号，开始编辑' }).click();
  await page.getByRole('heading', { name: '内容概览', exact: true }).waitFor();
  await page.getByText('正式官网已生成').waitFor();
  await page.screenshot({ path: path.join(qaDir, 'admin-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '游戏介绍', exact: true }).click();
  await page.getByLabel('游戏名称', { exact: true }).fill('云屿测试');
  await page.getByLabel('首页主标题', { exact: true }).fill('为远方写一封信\n我们的测试世界');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await page.getByText('草稿已保存，正式官网尚未改变', { exact: true }).waitFor();
  const guest = await context.newPage();
  await guest.goto(base); assert.ok((await guest.locator('h1').textContent()).includes('越过雾海'));
  await page.getByRole('button', { name: '下载设置', exact: true }).click();
  await page.getByLabel('下载地址').fill('https://example.com/game.zip');
  await page.getByLabel('版本号', { exact: true }).fill('v1.0.0-test');
  await page.getByLabel('提取码', { exact: true }).fill('abcd');
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/api/admin/publish') && response.status() === 200), page.getByRole('button', { name: '发布官网', exact: true }).click()]);
  await page.getByText('发布成功，官网 HTML 和图片已更新', { exact: true }).waitFor();
  await guest.reload(); assert.ok((await guest.locator('h1').textContent()).includes('为远方写一封信'));
  assert.equal(await guest.getByRole('link', { name: '下载游戏', exact: true }).getAttribute('href'), 'https://example.com/game.zip');
  await page.getByRole('button', { name: '首页轮播', exact: false }).first().click();
  await page.getByRole('button', { name: '从素材库添加', exact: true }).click();
  await page.getByRole('button', { name: '演示 · 林间星光' }).click();
  assert.equal(await page.locator('.slide-editor').count(), 4);
  await page.getByRole('button', { name: '上移图片', exact: true }).last().click();
  await page.getByRole('button', { name: '移除轮播图', exact: true }).last().click();
  assert.equal(await page.locator('.slide-editor').count(), 3);
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/api/admin/publish') && response.status() === 200), page.getByRole('button', { name: '发布官网', exact: true }).click()]);
  await page.getByText('发布成功，官网 HTML 和图片已更新', { exact: true }).waitFor();
  const canvasPng = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 800; canvas.height = 450; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#416b69'; ctx.fillRect(0, 0, 800, 450); ctx.fillStyle = '#efc38e'; ctx.beginPath(); ctx.arc(570, 160, 60, 0, Math.PI * 2); ctx.fill(); return canvas.toDataURL('image/png').split(',')[1]; });
  await page.getByRole('button', { name: '图片素材', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'test-landscape.png', mimeType: 'image/png', buffer: Buffer.from(canvasPng, 'base64') });
  await page.getByText('图片已添加到素材库', { exact: true }).waitFor();
  await page.getByText('test-landscape.png', { exact: true }).waitFor();
  await page.getByRole('button', { name: '内容概览', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出静态网站 ZIP', exact: false }).click();
  const download = await downloadPromise;
  await download.saveAs(path.join(qaDir, 'browser-export.zip'));
  const zip = unzipSync(await fs.readFile(path.join(qaDir, 'browser-export.zip')));
  assert.ok(strFromU8(zip['index.html']).includes('云屿测试'));
  const staticRequests = [];
  exportServer = http.createServer((req, res) => {
    const name = new URL(req.url, 'http://localhost').pathname.slice(1) || 'index.html';
    staticRequests.push(name);
    const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.svg': 'image/svg+xml', '.webp': 'image/webp', '.png': 'image/png' };
    res.writeHead(zip[name] ? 200 : 404, { 'Content-Type': types[path.extname(name)] || 'application/octet-stream' });
    res.end(zip[name] ? Buffer.from(zip[name]) : 'Not found');
  });
  await new Promise(resolve => exportServer.listen(0, '127.0.0.1', resolve));
  const staticPage = await context.newPage();
  await staticPage.goto(`http://127.0.0.1:${exportServer.address().port}`);
  await staticPage.getByRole('heading', { name: /为远方写一封信/ }).waitFor();
  await staticPage.getByRole('button', { name: '下一张', exact: true }).click();
  assert.equal(await staticPage.locator('[data-current]').textContent(), '02');
  assert.ok(!staticRequests.some(name => name.startsWith('api/')), '导出的官网不能依赖后端接口');
  assert.ok(await staticPage.locator('.gs-slide img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0)), '静态导出中的图片应能独立加载');
  await staticPage.close();
  await page.getByRole('button', { name: '查看生成的 HTML' }).click();
  await page.getByRole('heading', { name: '生成的静态 HTML' }).waitFor();
  await page.getByRole('button', { name: '关闭源码' }).click();
  await page.getByRole('button', { name: '查看发布记录' }).click();
  await page.getByRole('heading', { name: '发布记录', exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭发布记录' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(qaDir, 'admin-mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '后台手机页面不应横向溢出');
  await guest.setViewportSize({ width: 390, height: 844 }); await guest.reload();
  await guest.screenshot({ path: path.join(qaDir, 'homepage-mobile.png'), fullPage: true });
  assert.ok(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '官网手机页面不应横向溢出');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.getByRole('heading', { name: '欢迎回来' }).waitFor();
  await page.getByLabel('管理员账号').fill('tester');
  await page.locator('input[name="password"]').fill('browser-test-password');
  await page.getByRole('button', { name: '进入工作台' }).click();
  await page.getByRole('heading', { name: '内容概览', exact: true }).waitFor();
  assert.deepEqual(errors, [], `页面运行异常：${errors.join('; ')}`);
  assert.deepEqual(failures, [], `服务请求异常：${failures.join('; ')}`);
  console.log(JSON.stringify({ ok: true, mode: development ? 'development' : 'production', checks: ['官网轮播', '创建管理员', '草稿隔离', '发布与下载链接', '素材上传与压缩', '轮播排序', '静态 ZIP', 'HTML 与历史弹窗', '手机布局', '退出和重新登录'], screenshots: qaDir }, null, 2));
} finally {
  await browser?.close();
  await vite?.close();
  if (exportServer) await new Promise(resolve => exportServer.close(resolve));
  await new Promise(resolve => app.server.close(resolve));
  if (path.resolve(dataDir).startsWith(`${qaDir}${path.sep}browser-run-`)) await fs.rm(dataDir, { recursive: true, force: true });
}
